    /** Private raw-path constructor; no caller-created registry or parsed-object seam exists. */
    private class ValidatedCaptureInputRegistry private constructor(
        paths: CaptureInputPaths,
        limits: FullTreeClangCaptureInputLimits,
    ) : FullTreeClangCaptureInputRegistry {
        private val state = authenticate(paths, limits)

        override val artifactSha256: String = state.artifactSha256
        override val artifactBytes: Long = state.artifactBytes
        override val reportSha256: String = state.reportSha256
        override val configurationSha256: String = state.configurationSha256
        override val captureContextSha256: String = state.captureContextSha256
        override val captureActionsSha256: String = state.actionsSha256
        override val canonicalCaptureHeaderCandidateManifestSha256: String = state.headerManifestSha256
        override val actions: List<FullTreeClangCaptureAction> = Collections.unmodifiableList(
            ArrayList(state.actions),
        )
        override val canonicalCaptureHeaderCandidatePaths: List<String> = Collections.unmodifiableList(
            ArrayList(state.headerPaths),
        )
        override val sourceOnlyUnits: List<FullTreePlanningSourceOnlyUnit> = Collections.unmodifiableList(
            ArrayList(state.sourceOnlyUnits),
        )
        override val baseEnvironment: Map<String, String> = Collections.unmodifiableMap(
            LinkedHashMap(state.baseEnvironment),
        )
        override val blockerCodes: List<String> = Collections.unmodifiableList(ArrayList(state.blockerCodes))
        private val storedCanonicalBytes = state.canonicalBytes.copyOf()
        override val canonicalBytes: ByteArray
            get() = storedCanonicalBytes.copyOf()
        private val actionsByOwner: Map<String, FullTreeClangCaptureAction> = Collections.unmodifiableMap(
            LinkedHashMap<String, FullTreeClangCaptureAction>().apply {
                actions.forEach { action ->
                    if (action.moduleId != action.unitId || put(action.unitId, action) != null) {
                        captureFail("capture registry contains an invalid owner-module action identity")
                    }
                }
            },
        )

        override fun requireActionForOwnerModule(ownerUnitId: String): FullTreeClangCaptureAction {
            if (!ownerUnitId.matches(CAPTURE_COMPILATION_UNIT_ID)) {
                captureFail("capture action owner ID is invalid")
            }
            return actionsByOwner[ownerUnitId]
                ?: captureFail("capture action owner is outside the authenticated A13 population")
        }

        companion object {
            fun load(
                paths: CaptureInputPaths,
                limits: FullTreeClangCaptureInputLimits,
            ): FullTreeClangCaptureInputRegistry = ValidatedCaptureInputRegistry(paths, limits)
        }
    }
