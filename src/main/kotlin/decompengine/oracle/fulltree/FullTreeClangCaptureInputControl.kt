/** Caller-lowerable ceilings beneath the immutable Clang capture-input v1 policy. */
data class FullTreeClangCaptureInputLimits(
    val readiness: FullTreeHeaderPlanReadinessLimits = FullTreeHeaderPlanReadinessLimits(),
    val generated: FullTreeGeneratedFileInventoryLimits = FullTreeGeneratedFileInventoryLimits(),
    val maximumActions: Int = CAPTURE_MAXIMUM_ACTIONS,
    val maximumActionPathBytes: Long = CAPTURE_MAXIMUM_ACTION_PATH_BYTES,
    val maximumArgumentBytes: Int = CAPTURE_MAXIMUM_ARGUMENT_BYTES,
    val maximumArgumentsPerAction: Int = CAPTURE_MAXIMUM_ARGUMENTS_PER_ACTION,
    val maximumBaseEnvironmentVariables: Int = CAPTURE_MAXIMUM_BASE_ENVIRONMENT_VARIABLES,
    val maximumCanonicalBytes: Int = CAPTURE_MAXIMUM_CANONICAL_BYTES,
    val maximumCaptureHeaderCandidates: Int = CAPTURE_MAXIMUM_HEADER_CANDIDATES,
    val maximumCompilerBytes: Long = CAPTURE_MAXIMUM_COMPILER_BYTES,
    val maximumEnvironmentBytes: Long = CAPTURE_MAXIMUM_ENVIRONMENT_BYTES,
    val maximumHeaderPathBytes: Long = CAPTURE_MAXIMUM_HEADER_PATH_BYTES,
    val maximumOutputRecords: Long = CAPTURE_MAXIMUM_OUTPUT_RECORDS,
    val maximumPathBytes: Int = CAPTURE_MAXIMUM_PATH_BYTES,
    val maximumPathComponentBytes: Int = CAPTURE_MAXIMUM_PATH_COMPONENT_BYTES,
    val maximumSourceOnlyUnits: Int = CAPTURE_MAXIMUM_SOURCE_ONLY_UNITS,
    val maximumTotalArgumentBytes: Long = CAPTURE_MAXIMUM_TOTAL_ARGUMENT_BYTES,
    val maximumTotalArguments: Long = CAPTURE_MAXIMUM_TOTAL_ARGUMENTS,
    val maximumWorkUnits: Long = CAPTURE_MAXIMUM_WORK_UNITS,
) {
    init {
        require(maximumActions in 1..CAPTURE_MAXIMUM_ACTIONS)
        require(maximumActionPathBytes in 1L..CAPTURE_MAXIMUM_ACTION_PATH_BYTES)
        require(maximumArgumentBytes in 1..CAPTURE_MAXIMUM_ARGUMENT_BYTES)
        require(maximumArgumentsPerAction in 11..CAPTURE_MAXIMUM_ARGUMENTS_PER_ACTION)
        require(maximumBaseEnvironmentVariables in 3..CAPTURE_MAXIMUM_BASE_ENVIRONMENT_VARIABLES)
        require(maximumCanonicalBytes in 1..CAPTURE_MAXIMUM_CANONICAL_BYTES)
        require(maximumCaptureHeaderCandidates in 1..CAPTURE_MAXIMUM_HEADER_CANDIDATES)
        require(maximumCompilerBytes in 1L..CAPTURE_MAXIMUM_COMPILER_BYTES)
        require(maximumEnvironmentBytes in 1L..CAPTURE_MAXIMUM_ENVIRONMENT_BYTES)
        require(maximumHeaderPathBytes in 1L..CAPTURE_MAXIMUM_HEADER_PATH_BYTES)
        require(maximumOutputRecords in 1L..CAPTURE_MAXIMUM_OUTPUT_RECORDS)
        require(maximumPathBytes in 1..CAPTURE_MAXIMUM_PATH_BYTES)
        require(maximumPathComponentBytes in 1..CAPTURE_MAXIMUM_PATH_COMPONENT_BYTES)
        require(maximumSourceOnlyUnits in 1..CAPTURE_MAXIMUM_SOURCE_ONLY_UNITS)
        require(maximumTotalArgumentBytes in 1L..CAPTURE_MAXIMUM_TOTAL_ARGUMENT_BYTES)
        require(maximumTotalArguments in 11L..CAPTURE_MAXIMUM_TOTAL_ARGUMENTS)
        require(maximumWorkUnits in 1L..CAPTURE_MAXIMUM_WORK_UNITS)
    }
}

/**
 * One exact, unexecuted compiler argv joined by the loader to an authenticated A13 module.
 * The exposed object and dependency paths are required operands, not an exclusive write-set claim.
 */
sealed interface FullTreeClangCaptureAction {
    val actionSha256: String
    val moduleId: String
    val unitId: String
    val shardId: String
    val sourceKind: String
    val sourcePath: String
    val workingDirectory: String
    val mainInput: String
    val arguments: List<String>
    val objectOutput: String
    val dependencyFile: String
    val traceArtifactPath: String
}

/**
 * Integrity-validated, unexecuted capture input. The name intentionally omits "authenticated":
 * compiler actions have not been replayed from Ninja and generated bytes remain unreceipted.
 */
sealed interface FullTreeClangCaptureInputRegistry {
    val artifactSha256: String
    val artifactBytes: Long
    val reportSha256: String
    val configurationSha256: String
    val captureContextSha256: String
    val captureActionsSha256: String
    val canonicalCaptureHeaderCandidateManifestSha256: String
    val actions: List<FullTreeClangCaptureAction>
    val canonicalCaptureHeaderCandidatePaths: List<String>
    val sourceOnlyUnits: List<FullTreePlanningSourceOnlyUnit>
    val baseEnvironment: Map<String, String>
    val blockerCodes: List<String>
    val canonicalBytes: ByteArray

    fun requireActionForOwnerModule(ownerUnitId: String): FullTreeClangCaptureAction
}

/** Load-only Kotlin/JVM validation. This object cannot generate, publish, rewrite, or execute actions. */
object FullTreeClangCaptureInputControl {
    val configurationSha256: String by lazy {
        OracleSchemas.configurationSha256(CAPTURE_SCHEMA, CAPTURE_CONFIGURATION_POLICY)
    }

    fun loadAndValidate(
        path: Path,
        headerPlanReadinessPath: Path,
        generatedFileInventoryPath: Path,
        sourceArchivePath: Path,
        generatedTreeArchivePath: Path,
        generatedProvenancePath: Path,
        scopePath: Path,
        sourceLockPath: Path,
        artifactManifestPath: Path,
        buildRecordPath: Path,
        inventoryPath: Path,
        sourceInventoryPath: Path,
        planningInventoryPath: Path,
        limits: FullTreeClangCaptureInputLimits = FullTreeClangCaptureInputLimits(),
    ): FullTreeClangCaptureInputRegistry = ValidatedCaptureInputRegistry.load(
        CaptureInputPaths(
            artifact = path,
            readiness = headerPlanReadinessPath,
            generatedInventory = generatedFileInventoryPath,
            sourceArchive = sourceArchivePath,
            generatedArchive = generatedTreeArchivePath,
            generatedProvenance = generatedProvenancePath,
            scope = scopePath,
            sourceLock = sourceLockPath,
            artifactManifest = artifactManifestPath,
            buildRecord = buildRecordPath,
            inventory = inventoryPath,
            sourceInventory = sourceInventoryPath,
            planningInventory = planningInventoryPath,
        ),
        limits,
    )

    private fun authenticate(
        paths: CaptureInputPaths,
        limits: FullTreeClangCaptureInputLimits,
    ): ValidatedCaptureInputState {
        requireDistinctCaptureInputs(paths)
        StableControlFile.open(
            paths.artifact,
            limits.maximumCanonicalBytes.toLong(),
            "full-tree Clang capture input",
        ).use { artifact ->
            artifact.requireSingleLink("full-tree Clang capture input")
            val (document, bytes) = readStableCaptureObject(artifact, limits)
            validateCaptureReportHash(document, limits.maximumCanonicalBytes)

            val predecessors = authenticateCapturePredecessors(paths, limits)
            val actions = validateCaptureActions(document, predecessors, limits)
            val expected = buildExpectedCaptureDocument(predecessors, actions, limits)
            if (document != expected) {
                captureFail("Clang capture input differs from its revalidated raw predecessors and actions")
            }
            if (bytes.size > limits.maximumCanonicalBytes) {
                captureFail("Clang capture input exceeds its caller-lowered canonical byte bound")
            }

            artifact.verifyUnchanged("full-tree Clang capture input")
            val terminal = authenticateCapturePredecessors(paths, limits)
            if (capturePredecessorSnapshot(terminal) != capturePredecessorSnapshot(predecessors)) {
                captureFail("Clang capture input predecessors changed during validation")
            }
            artifact.verifyUnchanged("full-tree Clang capture input")
            return validatedCaptureState(
                document,
                bytes,
                actions,
                predecessors,
            )
        }
    }

    private fun authenticateCapturePredecessors(
        paths: CaptureInputPaths,
        limits: FullTreeClangCaptureInputLimits,
    ): CapturePredecessors {
        val readiness = FullTreeHeaderPlanReadinessControl.loadAndValidate(
            paths.readiness,
            paths.sourceArchive,
            paths.scope,
            paths.sourceLock,
            paths.artifactManifest,
            paths.buildRecord,
            paths.inventory,
            paths.sourceInventory,
            paths.planningInventory,
            limits.readiness,
        )
        val generated = FullTreeGeneratedFileInventoryControl.loadAndValidate(
            paths.generatedInventory,
            paths.generatedArchive,
            paths.generatedProvenance,
            paths.scope,
            paths.sourceLock,
            paths.artifactManifest,
            paths.buildRecord,
            paths.inventory,
            paths.sourceInventory,
            paths.planningInventory,
            limits.generated,
        )
        val (planningDocument, planningBytes) = readCanonicalControlObject(
            paths.planningInventory,
            limits.generated.planning.maximumSerializedBytes,
            "full-tree planning inventory",
            "full-tree-planning-inventory",
        )
        if (OracleArtifacts.sha256(planningBytes) != readiness.planningInventoryArtifactSha256 ||
            readiness.planningInventoryArtifactSha256 != generatedPlanningArtifactSha256(
                paths.generatedInventory,
                generated,
                limits,
            )
        ) {
            captureFail("capture predecessors disagree on the planning inventory artifact")
        }
        val (generatedDocument, generatedBytes) = readCanonicalControlObject(
            paths.generatedInventory,
            limits.generated.maximumSerializedBytes,
            "full-tree generated-file inventory",
            "full-tree-generated-file-inventory",
        )
        if (OracleArtifacts.sha256(generatedBytes) != generated.artifactSha256) {
            captureFail("generated-file registry artifact changed after validation")
        }
        val generatedOracle = generatedDocument.controlObject("oracle")
        if (generatedOracle.controlString("planningInventoryArtifactSha256") !=
            readiness.planningInventoryArtifactSha256 ||
            generatedOracle.controlString("planningInventoryReportSha256") !=
            readiness.planningInventoryReportSha256 ||
            generatedOracle.controlString("planningInventoryConfigurationSha256") !=
            readiness.planningInventoryConfigurationSha256
        ) {
            captureFail("generated-file registry planning bindings do not reconcile with readiness")
        }
        val (buildRecord, buildRecordBytes) = readCanonicalControlObject(
            paths.buildRecord,
            limits.generated.planning.control.maximumBuildRecordBytes,
            "build record",
            "build-record",
        )
        val buildRecordSha256 = OracleArtifacts.sha256(buildRecordBytes)
        val planningOracle = planningDocument.controlObject("oracle")
        if (planningOracle.controlString("buildRecordSha256") != buildRecordSha256 ||
            generatedOracle.controlString("buildRecordSha256") != buildRecordSha256
        ) {
            captureFail("capture predecessor build-record commitments do not reconcile")
        }
        val context = expectedCaptureContext(
            readiness,
            generated,
            planningDocument,
            buildRecord,
            buildRecordSha256,
            generatedDocument,
            limits,
        )
        return CapturePredecessors(readiness, generated, context)
    }

    private fun generatedPlanningArtifactSha256(
        generatedInventoryPath: Path,
        generated: FullTreeGeneratedFileRegistry,
        limits: FullTreeClangCaptureInputLimits,
    ): String {
        val (document, bytes) = readCanonicalControlObject(
            generatedInventoryPath,
            limits.generated.maximumSerializedBytes,
            "full-tree generated-file inventory",
            "full-tree-generated-file-inventory",
        )
        if (OracleArtifacts.sha256(bytes) != generated.artifactSha256) {
            captureFail("generated-file registry artifact changed after validation")
        }
        return document.controlObject("oracle").controlString("planningInventoryArtifactSha256")
    }

    private fun expectedCaptureContext(
        readiness: AuthenticatedFullTreeHeaderPlanReadiness,
        generated: FullTreeGeneratedFileRegistry,
        planningDocument: JsonObject,
        buildRecord: JsonObject,
        buildRecordSha256: String,
        generatedDocument: JsonObject,
        limits: FullTreeClangCaptureInputLimits,
    ): CaptureExpectedContext {
        if (readiness.sourceModules.size !in 1..limits.maximumActions) {
            captureFail("authenticated A13 module population exceeds the capture action bound")
        }
        if (readiness.sourceOnlyUnits.size > limits.maximumSourceOnlyUnits) {
            captureFail("source-only population exceeds the capture bound")
        }
        val directories = buildRecord.controlObject("directories")
        val sourceRoot = requireCaptureAbsolutePath(
            directories.controlString("source"),
            "build-record source root",
            limits,
        )
        val buildRoot = requireCaptureAbsolutePath(
            directories.controlString("build"),
            "build-record build root",
            limits,
        )
        val installRoot = requireCaptureAbsolutePath(
            directories.controlString("install"),
            "build-record install root",
            limits,
        )
        requireDisjointCaptureRoots(sourceRoot, buildRoot, installRoot)

        val commands = buildRecord.controlObject("commands")
        val configure = commands.controlArray("configure")
        val cDriver = configuredDriver(configure, "-DCMAKE_C_COMPILER=", "C compiler", limits)
        val cxxDriver = configuredDriver(configure, "-DCMAKE_CXX_COMPILER=", "C++ compiler", limits)
        val compilerTool = buildRecord.controlArray("tools").controlObjects("build-record tools")
            .singleOrNull { it.controlString("role") == "compiler" }
            ?: captureFail("build record must contain exactly one compiler tool")
        val compilerBinding = captureToolBinding(compilerTool, "compiler", limits.maximumCompilerBytes)
        if (compilerBinding.controlString("path") != cDriver) {
            captureFail("recorded compiler identity does not bind the configured C driver")
        }
        val compilerIdentity = captureCanonicalCommitment(CAPTURE_COMPILER_IDENTITY_DOMAIN, compilerBinding)

        val variables = buildRecord.controlObject("environment").controlObject("variables")
        val environment = captureEnvironment(variables, limits)
        val container = buildRecord.controlObject("environment").controlObject("container")
        val generatedBuildGraph = generatedDocument.controlObject("provenance").controlObject("buildGraph")
        val expectedBuild = captureBuildDocument(
            sourceRoot,
            buildRoot,
            installRoot,
            container,
            commands,
            generatedBuildGraph,
            buildRecordSha256,
        )

        val sourceHeaders = readiness.authenticatedSourceHeaderCandidatePaths
        val generatedHeaders = generated.canonicalGeneratedHeaderPaths
        val captureHeaders = TreeSet<String>(FULL_TREE_CODE_POINT_ORDER)
        var headerPathBytes = 0L
        (sourceHeaders + generatedHeaders).forEach { path ->
            requireCaptureHeaderCandidatePath(path, limits)
            headerPathBytes = captureAddExact(
                headerPathBytes,
                path.toByteArray(StandardCharsets.UTF_8).size.toLong(),
                "capture header-path byte",
            )
            if (headerPathBytes > limits.maximumHeaderPathBytes) {
                captureFail("capture header candidate paths exceed their aggregate byte bound")
            }
            if (!captureHeaders.add(path)) captureFail("capture header candidate population overlaps")
        }
        if (captureHeaders.size > limits.maximumCaptureHeaderCandidates) {
            captureFail("capture header candidate population exceeds its bound")
        }

        val modules = readiness.sourceModules.map { module ->
            val physicalInput = captureModuleInput(module, sourceRoot, buildRoot, limits)
            CaptureModule(
                module.moduleId,
                module.unitId,
                module.shardId,
                module.sourceKind,
                module.sourcePath,
                physicalInput,
            )
        }
        if (modules.map(CaptureModule::unitId).toSet().size != modules.size ||
            modules.map(CaptureModule::sourcePath).toSet().size != modules.size ||
            modules.map(CaptureModule::mainInput).toSet().size != modules.size
        ) {
            captureFail("authenticated A13 module identities do not form an exact capture population")
        }
        reconcileGeneratedModules(modules, generated)

        val planningOracle = planningDocument.controlObject("oracle")
        val generatedCounts = generatedDocument.controlObject("counts")
        val oracleDocument = JsonObject(
            mapOf(
                "artifactManifestSha256" to planningOracle.getValue("artifactManifestSha256"),
                "buildRecordSha256" to JsonPrimitive(buildRecordSha256),
                "configurationSha256" to JsonPrimitive(configurationSha256),
                "generatedFileInventoryArtifactBytes" to JsonPrimitive(generated.artifactBytes),
                "generatedFileInventoryArtifactSha256" to JsonPrimitive(generated.artifactSha256),
                "generatedFileInventoryConfigurationSha256" to JsonPrimitive(generated.configurationSha256),
                "generatedFileInventoryReportSha256" to JsonPrimitive(generated.reportSha256),
                "headerPlanReadinessArtifactBytes" to JsonPrimitive(readiness.artifactBytes),
                "headerPlanReadinessArtifactSha256" to JsonPrimitive(readiness.artifactSha256),
                "headerPlanReadinessConfigurationSha256" to JsonPrimitive(readiness.configurationSha256),
                "headerPlanReadinessReportSha256" to JsonPrimitive(readiness.reportSha256),
                "id" to buildRecord.controlObject("oracle").getValue("id"),
                "inventoryArtifactSha256" to planningOracle.getValue("inventoryArtifactSha256"),
                "planningInventoryArtifactSha256" to JsonPrimitive(readiness.planningInventoryArtifactSha256),
                "planningInventoryConfigurationSha256" to JsonPrimitive(
                    readiness.planningInventoryConfigurationSha256,
                ),
                "planningInventoryReportSha256" to JsonPrimitive(readiness.planningInventoryReportSha256),
                "scopeSha256" to planningOracle.getValue("scopeSha256"),
                "sourceInventoryArtifactSha256" to planningOracle.getValue("sourceInventoryArtifactSha256"),
                "sourceLockSha256" to planningOracle.getValue("sourceLockSha256"),
            ),
        )
        val sourceDocument = JsonObject(
            mapOf(
                "archiveSha256" to JsonPrimitive(readiness.sourceArchiveSha256),
                "dependencyArtifactSha256" to JsonPrimitive(readiness.sourceDependencyArtifactSha256),
                "dependencyConfigurationSha256" to JsonPrimitive(
                    readiness.sourceDependencyConfigurationSha256,
                ),
                "dependencyReportSha256" to JsonPrimitive(readiness.sourceDependencyReportSha256),
                "headerCandidateManifestSha256" to JsonPrimitive(readiness.sourceHeaderManifestSha256),
                "headerCandidates" to JsonPrimitive(sourceHeaders.size),
            ),
        )
        val generatedDocumentSummary = JsonObject(
            mapOf(
                "archiveSha256" to JsonPrimitive(generated.archiveSha256),
                "buildGraphProvenanceSha256" to JsonPrimitive(generated.buildGraphProvenanceSha256),
                "canonicalFileManifestSha256" to JsonPrimitive(generated.canonicalGeneratedFileManifestSha256),
                "canonicalHeaderManifestSha256" to JsonPrimitive(
                    generated.canonicalGeneratedHeaderManifestSha256,
                ),
                "files" to JsonPrimitive(generated.generatedFiles.size),
                "generationReceiptBound" to JsonPrimitive(false),
                "headers" to JsonPrimitive(generated.generatedHeaders.size),
                "provenanceSha256" to JsonPrimitive(generated.provenanceSha256),
                "snapshotBytesAuthenticated" to JsonPrimitive(false),
                "snapshotBytesIntegrityVerified" to JsonPrimitive(true),
                "translationUnits" to JsonPrimitive(generated.generatedTranslationUnits.size),
            ),
        )
        if (generatedCounts.controlLong("generatedFiles") != generated.generatedFiles.size.toLong() ||
            generatedCounts.controlLong("generatedHeaders") != generated.generatedHeaders.size.toLong() ||
            generatedCounts.controlLong("generatedTranslationUnits") !=
            generated.generatedTranslationUnits.size.toLong()
        ) {
            captureFail("generated-file registry public population differs from its artifact")
        }
        val compilerDocument = JsonObject(
            mapOf(
                "cDriverPath" to JsonPrimitive(cDriver),
                "cxxDriverIdentityAuthenticated" to JsonPrimitive(false),
                "cxxDriverPath" to JsonPrimitive(cxxDriver),
                "recordedTool" to compilerBinding,
                "recordedToolIdentitySha256" to JsonPrimitive(compilerIdentity),
            ),
        )
        val headerManifestSha256 = CaptureCommitment(CAPTURE_HEADER_MANIFEST_DOMAIN).apply {
            long(captureHeaders.size.toLong())
            captureHeaders.forEach { path -> token(path.toByteArray(StandardCharsets.UTF_8)) }
        }.finish()
        val captureContextSha256 = captureCanonicalCommitment(
            CAPTURE_CONTEXT_DOMAIN,
            captureContextDocument(
                oracleDocument,
                sourceDocument,
                generatedDocumentSummary,
                compilerDocument,
                expectedBuild,
                environment.document,
                headerManifestSha256,
            ),
        )
        return CaptureExpectedContext(
            planningDocument = planningDocument,
            buildRecord = buildRecord,
            buildRecordSha256 = buildRecordSha256,
            generatedInventoryDocument = generatedDocument,
            oracleDocument = oracleDocument,
            sourceDocument = sourceDocument,
            generatedDocument = generatedDocumentSummary,
            compilerDocument = compilerDocument,
            buildDocument = expectedBuild,
            environmentDocument = environment.document,
            baseEnvironment = environment.variables,
            baseEnvironmentSha256 = environment.sha256,
            environmentBytes = environment.bytes,
            captureContextSha256 = captureContextSha256,
            headerManifestSha256 = headerManifestSha256,
            buildRoot = buildRoot,
            cDriver = cDriver,
            cxxDriver = cxxDriver,
            sourceArchiveSha256 = readiness.sourceArchiveSha256,
            modules = modules,
            sourceOnlyUnits = readiness.sourceOnlyUnits,
            sourceHeaderCount = sourceHeaders.size,
            generatedHeaderCount = generatedHeaders.size,
            headerPaths = Collections.unmodifiableList(ArrayList(captureHeaders)),
            headerPathBytes = headerPathBytes,
            generatedTranslationUnits = generated.generatedTranslationUnits.associateBy { it.unitId },
        )
    }

    private fun captureEnvironment(
        variables: JsonObject,
        limits: FullTreeClangCaptureInputLimits,
    ): CaptureEnvironment {
        if (variables.size !in 3..limits.maximumBaseEnvironmentVariables) {
            captureFail("build-record base environment exceeds the capture variable bound")
        }
        val records = variables.entries.map { (name, rawValue) ->
            if (!name.matches(CAPTURE_ENVIRONMENT_NAME) ||
                CAPTURE_FORBIDDEN_ENVIRONMENT_PREFIXES.any(name::startsWith) ||
                name in CAPTURE_FORBIDDEN_ENVIRONMENT_NAMES
            ) {
                captureFail("build-record base environment contains a forbidden capture variable")
            }
            val value = (rawValue as? JsonPrimitive)?.takeIf { it.isString }?.content
                ?: captureFail("build-record base environment value is not a string")
            if ('\u0000' in value) {
                captureFail("build-record base environment contains a NUL value")
            }
            JsonObject(mapOf("name" to JsonPrimitive(name), "value" to JsonPrimitive(value)))
        }.sortedWith(compareBy(FULL_TREE_CODE_POINT_ORDER) { it.controlString("name") })
        if (records.map { it.controlString("name") }.toSet().size != records.size) {
            captureFail("build-record base environment duplicates a variable")
        }
        var environmentBytes = 0L
        val retained = LinkedHashMap<String, String>()
        records.forEach { record ->
            val name = record.controlString("name")
            val value = record.controlString("value")
            environmentBytes = captureAddExact(
                environmentBytes,
                name.toByteArray(StandardCharsets.UTF_8).size.toLong(),
                "capture environment byte",
            )
            environmentBytes = captureAddExact(
                environmentBytes,
                value.toByteArray(StandardCharsets.UTF_8).size.toLong(),
                "capture environment byte",
            )
            if (environmentBytes > limits.maximumEnvironmentBytes) {
                captureFail("build-record base environment exceeds its byte bound")
            }
            retained[name] = value
        }
        val recordsArray = JsonArray(records)
        val sha256 = captureCanonicalCommitment(CAPTURE_ENVIRONMENT_DOMAIN, recordsArray)
        return CaptureEnvironment(
            document = JsonObject(
                mapOf(
                    "baseEnvironmentSha256" to JsonPrimitive(sha256),
                    "baseVariables" to recordsArray,
                    "fixedCaptureVariables" to CAPTURE_FIXED_ENVIRONMENT,
                    "inheritedEnvironment" to JsonPrimitive("cleared"),
                    "perActionHeaderOutput" to CAPTURE_PER_ACTION_ENVIRONMENT,
                ),
            ),
            variables = Collections.unmodifiableMap(retained),
            sha256 = sha256,
            bytes = environmentBytes,
        )
    }

    private fun captureBuildDocument(
        sourceRoot: String,
        buildRoot: String,
        installRoot: String,
        container: JsonObject,
        commands: JsonObject,
        generatedBuildGraph: JsonObject,
        buildRecordSha256: String,
    ): JsonObject {
        if (generatedBuildGraph.controlString("buildRecordSha256") != buildRecordSha256 ||
            generatedBuildGraph.controlString("buildDirectory") != buildRoot ||
            generatedBuildGraph.controlString("buildSystem") != "cmake-ninja"
        ) {
            captureFail("generated build graph does not reconcile with the capture build record")
        }
        val configureSha256 = fullTreeGeneratedConfigureCommandSha256(commands.controlArray("configure"))
        val compileSha256 = fullTreeGeneratedCompileCommandSha256(commands.controlArray("compile"))
        if (generatedBuildGraph.controlString("configureCommandSha256") != configureSha256 ||
            generatedBuildGraph.controlString("compileCommandSha256") != compileSha256
        ) {
            captureFail("generated build graph command commitments do not reconcile")
        }
        return JsonObject(
            mapOf(
                "buildDirectory" to JsonPrimitive(buildRoot),
                "cmakeCacheBytes" to generatedBuildGraph.getValue("cmakeCacheBytes"),
                "cmakeCacheSha256" to generatedBuildGraph.getValue("cmakeCacheSha256"),
                "cmakeTool" to generatedBuildGraph.getValue("cmakeTool"),
                "compileCommandSha256" to JsonPrimitive(compileSha256),
                "configureCommandSha256" to JsonPrimitive(configureSha256),
                "containerDigest" to container.getValue("digest"),
                "containerImage" to container.getValue("image"),
                "installDirectory" to JsonPrimitive(installRoot),
                "ninjaManifestBytes" to generatedBuildGraph.getValue("ninjaManifestBytes"),
                "ninjaManifestSha256" to generatedBuildGraph.getValue("ninjaManifestSha256"),
                "ninjaTool" to generatedBuildGraph.getValue("ninjaTool"),
                "platform" to container.getValue("platform"),
                "sourceDateEpoch" to generatedBuildGraph.getValue("sourceDateEpoch"),
                "sourceDirectory" to JsonPrimitive(sourceRoot),
            ),
        )
    }

    private fun configuredDriver(
        configure: JsonArray,
        prefix: String,
        label: String,
        limits: FullTreeClangCaptureInputLimits,
    ): String {
        val matches = configure.map { value -> value.controlString("configure command") }
            .filter { it.startsWith(prefix) }
        if (matches.size != 1) captureFail("build record must configure exactly one $label path")
        val path = matches.single().removePrefix(prefix)
        return requireCaptureAbsolutePath(path, "configured $label", limits)
    }

    private fun captureToolBinding(
        tool: JsonObject,
        expectedRole: String,
        maximumBytes: Long,
    ): JsonObject {
        val path = tool.controlString("path")
        val versionCommand = tool.controlArray("versionCommand")
        if (versionCommand.firstOrNull()?.controlString("compiler version command") != path) {
            captureFail("$expectedRole version command does not start with its executable path")
        }
        val executableBytes = tool.controlLong("executableBytes")
        if (executableBytes !in 1L..maximumBytes) {
            captureFail("$expectedRole executable exceeds the capture tool byte bound")
        }
        return JsonObject(
            mapOf(
                "executableBytes" to JsonPrimitive(executableBytes),
                "executableSha256" to JsonPrimitive(tool.controlString("executableSha256")),
                "path" to JsonPrimitive(path),
                "role" to JsonPrimitive(expectedRole),
                "versionOutputSha256" to JsonPrimitive(
                    OracleArtifacts.sha256(tool.controlString("versionOutput").toByteArray(StandardCharsets.UTF_8)),
                ),
            ),
        )
    }

    private fun captureModuleInput(
        module: FullTreePlanningSourceModule,
        sourceRoot: String,
        buildRoot: String,
        limits: FullTreeClangCaptureInputLimits,
    ): String {
        if (module.moduleId != module.unitId || !module.unitId.matches(CAPTURE_COMPILATION_UNIT_ID)) {
            captureFail("capture module has an invalid A13 identity")
        }
        val (prefix, root) = when (module.sourceKind) {
            "handwritten" -> "source/" to sourceRoot
            "generated" -> "generated/" to buildRoot
            else -> captureFail("capture module has an unsupported source kind")
        }
        if (!module.sourcePath.startsWith(prefix)) {
            captureFail("capture module path differs from its source kind")
        }
        val suffix = module.sourcePath.removePrefix(prefix)
        requireCaptureRelativePath(suffix, "capture module source", limits)
        return "$root/$suffix"
    }

    private fun reconcileGeneratedModules(
        modules: List<CaptureModule>,
        generated: FullTreeGeneratedFileRegistry,
    ) {
        val generatedModules = modules.filter { it.sourceKind == "generated" }
        if (generatedModules.size != generated.generatedTranslationUnits.size) {
            captureFail("generated capture action population differs from the generated-file registry")
        }
        generatedModules.forEach { module ->
            val byOwner = generated.requireGeneratedTranslationUnit(module.unitId)
            val byPath = generated.requireGeneratedFile(module.sourcePath)
            if (byPath !is FullTreeGeneratedTranslationUnit || byPath != byOwner ||
                byOwner.moduleId != module.moduleId || byOwner.unitId != module.unitId ||
                byOwner.shardId != module.shardId || byOwner.sourcePath != module.sourcePath
            ) {
                captureFail("generated capture module does not reconcile with its generated-file identity")
            }
        }
    }

    private fun validateCaptureActions(
        document: JsonObject,
        predecessors: CapturePredecessors,
        limits: FullTreeClangCaptureInputLimits,
    ): ValidatedCaptureActions {
        val context = predecessors.context
        val rawActions = document.controlArray("actions").controlObjects("Clang capture actions")
        if (rawActions.size != context.modules.size || rawActions.size > limits.maximumActions) {
            captureFail("Clang capture actions do not cover the authenticated A13 module population exactly")
        }
        val objectOutputs = HashSet<String>()
        val dependencyFiles = HashSet<String>()
        var argumentCount = 0L
        var argumentBytes = 0L
        var actionPathBytes = 0L
        val actions = ArrayList<ValidatedClangCaptureAction>(rawActions.size)

        rawActions.forEachIndexed { index, action ->
            val module = context.modules[index]
            val workingDirectory = action.controlString("workingDirectory")
            val mainInput = action.controlString("mainInput")
            requireCaptureAbsolutePath(workingDirectory, "capture action working directory", limits)
            requireCaptureAbsolutePath(mainInput, "capture action main input", limits)
            if (workingDirectory != context.buildRoot || mainInput != module.mainInput) {
                captureFail("capture action order or physical module mapping differs from authenticated A13")
            }
            val rawArguments = action.controlArray("arguments")
            if (rawArguments.size !in 11..limits.maximumArgumentsPerAction) {
                captureFail("capture action argument population exceeds its bound")
            }
            argumentCount = captureAddExact(
                argumentCount,
                rawArguments.size.toLong(),
                "capture argument",
            )
            if (argumentCount > limits.maximumTotalArguments) {
                captureFail("capture action population exceeds its aggregate argument bound")
            }
            val arguments = rawArguments.map { value ->
                val argument = value.controlString("capture argument")
                val bytes = argument.toByteArray(StandardCharsets.UTF_8).size
                if (argument.isEmpty() || bytes > limits.maximumArgumentBytes ||
                    argument.any { it == '\u0000' || it == '\r' || it == '\n' }
                ) {
                    captureFail("capture argument violates its canonical byte profile")
                }
                argumentBytes = captureAddExact(argumentBytes, bytes.toLong(), "capture argument byte")
                if (argumentBytes > limits.maximumTotalArgumentBytes) {
                    captureFail("capture action population exceeds its aggregate argument-byte bound")
                }
                argument
            }
            val validated = validateCaptureCommand(
                module,
                workingDirectory,
                mainInput,
                arguments,
                context,
                limits,
            )
            if (!objectOutputs.add(validated.objectOutput) ||
                !dependencyFiles.add(validated.dependencyFile) ||
                validated.objectOutput in dependencyFiles ||
                validated.dependencyFile in objectOutputs
            ) {
                captureFail("capture actions collide on an object or dependency output")
            }
            listOf(workingDirectory, mainInput, validated.objectOutput, validated.dependencyFile).forEach { path ->
                actionPathBytes = captureAddExact(
                    actionPathBytes,
                    path.toByteArray(StandardCharsets.UTF_8).size.toLong(),
                    "capture action-path byte",
                )
                if (actionPathBytes > limits.maximumActionPathBytes) {
                    captureFail("capture action paths exceed their aggregate byte bound")
                }
            }
            actions += validated
        }
        val expectedUnits = context.modules.map(CaptureModule::unitId).toSet()
        if (actions.map(ValidatedClangCaptureAction::unitId).toSet() != expectedUnits) {
            captureFail("capture action owner coverage differs from authenticated A13")
        }
        val actionsSha256 = CaptureCommitment(CAPTURE_ACTION_MANIFEST_DOMAIN).apply {
            long(actions.size.toLong())
            actions.forEach { action -> token(action.actionSha256.toByteArray(StandardCharsets.US_ASCII)) }
        }.finish()
        return ValidatedCaptureActions(
            documents = rawActions,
            actions = Collections.unmodifiableList(actions),
            actionsSha256 = actionsSha256,
            argumentCount = argumentCount,
            argumentBytes = argumentBytes,
            actionPathBytes = actionPathBytes,
        )
    }

    private fun validateCaptureCommand(
        module: CaptureModule,
        workingDirectory: String,
        mainInput: String,
        arguments: List<String>,
        context: CaptureExpectedContext,
        limits: FullTreeClangCaptureInputLimits,
    ): ValidatedClangCaptureAction {
        val expectedDriver = when {
            module.sourcePath.endsWith(".c") || module.sourcePath.endsWith(".S") -> context.cDriver
            module.sourcePath.endsWith(".cpp") -> context.cxxDriver
            else -> captureFail("capture module has an unsupported compiler-driver suffix")
        }
        if (arguments.firstOrNull() != expectedDriver) {
            captureFail("capture action does not start with its configured language driver")
        }
        if (arguments.size < CAPTURE_COMPILE_FRAME_SIZE ||
            arguments[1] != "--no-default-config" ||
            arguments[2] != "-MD" ||
            arguments[3] != "-MT" ||
            arguments[5] != "-MF" ||
            arguments[7] != "-o" ||
            arguments[9] != "-c" ||
            arguments[10] != mainInput
        ) {
            captureFail("capture action does not use the fixed compiler-frame grammar")
        }
        if (arguments.count { it == "--no-default-config" } != 1 ||
            arguments.count { it == "-MD" } != 1 ||
            arguments.count { it == "-c" } != 1 ||
            arguments.count { it == mainInput } != 1
        ) {
            captureFail("capture action duplicates a fixed compiler-frame token")
        }
        if (arguments.drop(CAPTURE_COMPILE_FRAME_SIZE).any { !it.startsWith('-') }) {
            captureFail("capture action tail must contain only dash-prefixed tokens")
        }
        val usesIndirectArguments = arguments.any { argument ->
            argument.startsWith('@') || argument.startsWith("--config")
        }
        if (usesIndirectArguments) {
            captureFail("capture action response and compiler-config files are forbidden")
        }
        val usesOpaqueForwarding = arguments.any { argument ->
            CAPTURE_OPAQUE_FORWARDING_PREFIXES.any(argument::startsWith)
        }
        if (usesOpaqueForwarding) {
            captureFail("capture action opaque compiler forwarding is forbidden")
        }
        if (arguments.any { it.startsWith("-x") }) {
            captureFail("capture action language overrides are forbidden")
        }
        if (arguments.any { it in CAPTURE_FORBIDDEN_ARGUMENTS }) {
            captureFail("capture action contains a forbidden non-compiling or mutating mode")
        }
        CAPTURE_CAPTURE_OPTION_PREFIXES.forEach { prefix ->
            if (arguments.any { it == prefix || it.startsWith("$prefix=") }) {
                captureFail("capture action must not author the host-owned header-capture overlay")
            }
        }
        val target = requireCaptureOption(arguments, "-MT")
        val depfileRaw = requireCaptureOption(arguments, "-MF")
        val outputRaw = requireCaptureOption(arguments, "-o")
        if (target != outputRaw || depfileRaw != "$outputRaw.d") {
            captureFail("capture action target, object, and dependency-file operands do not reconcile")
        }
        val objectOutput = resolveCaptureBuildOutput(workingDirectory, outputRaw, context.buildRoot, limits)
        val dependencyFile = resolveCaptureBuildOutput(workingDirectory, depfileRaw, context.buildRoot, limits)
        if (objectOutput == dependencyFile) captureFail("capture object and dependency outputs overlap")

        val generatedEvidence = if (module.sourceKind == "generated") {
            context.generatedTranslationUnits[module.unitId]
                ?: captureFail("generated capture action has no generated-file evidence")
        } else {
            null
        }
        val actionSha256 = CaptureCommitment(CAPTURE_ACTION_DOMAIN).apply {
            token(configurationSha256.toByteArray(StandardCharsets.US_ASCII))
            token(context.captureContextSha256.toByteArray(StandardCharsets.US_ASCII))
            token(context.buildRecordSha256.toByteArray(StandardCharsets.US_ASCII))
            token(context.baseEnvironmentSha256.toByteArray(StandardCharsets.US_ASCII))
            token(module.moduleId.toByteArray(StandardCharsets.UTF_8))
            token(module.unitId.toByteArray(StandardCharsets.UTF_8))
            token(module.shardId.toByteArray(StandardCharsets.UTF_8))
            token(module.sourceKind.toByteArray(StandardCharsets.UTF_8))
            token(module.sourcePath.toByteArray(StandardCharsets.UTF_8))
            if (generatedEvidence == null) {
                token("source-archive".toByteArray(StandardCharsets.US_ASCII))
                token(context.sourceArchiveSha256.toByteArray(StandardCharsets.US_ASCII))
            } else {
                token("generated-file".toByteArray(StandardCharsets.US_ASCII))
                long(generatedEvidence.bytes)
                token(generatedEvidence.sha256.toByteArray(StandardCharsets.US_ASCII))
                token(generatedEvidence.generatorActionSha256.toByteArray(StandardCharsets.US_ASCII))
            }
            token(workingDirectory.toByteArray(StandardCharsets.UTF_8))
            token(mainInput.toByteArray(StandardCharsets.UTF_8))
            long(arguments.size.toLong())
            arguments.forEach { argument -> token(argument.toByteArray(StandardCharsets.UTF_8)) }
            token(objectOutput.toByteArray(StandardCharsets.UTF_8))
            token(dependencyFile.toByteArray(StandardCharsets.UTF_8))
        }.finish()
        return ValidatedClangCaptureAction(
            actionSha256 = actionSha256,
            moduleId = module.moduleId,
            unitId = module.unitId,
            shardId = module.shardId,
            sourceKind = module.sourceKind,
            sourcePath = module.sourcePath,
            workingDirectory = workingDirectory,
            mainInput = mainInput,
            arguments = Collections.unmodifiableList(ArrayList(arguments)),
            objectOutput = objectOutput,
            dependencyFile = dependencyFile,
            traceArtifactPath = "traces/$actionSha256.json",
        )
    }

    private fun requireCaptureOption(arguments: List<String>, option: String): String {
        if (arguments.any { argument -> argument != option && argument.startsWith(option) }) {
            captureFail("capture action uses a joined or ambiguous $option option")
        }
        val indexes = arguments.indices.filter { arguments[it] == option }
        if (indexes.size != 1 || indexes.single() == arguments.lastIndex) {
            captureFail("capture action must contain exactly one separate $option operand")
        }
        val value = arguments[indexes.single() + 1]
        if (value == "-" || value.startsWith('-')) {
            captureFail("capture action $option output is invalid")
        }
        return value
    }

    private fun resolveCaptureBuildOutput(
        workingDirectory: String,
        raw: String,
        buildRoot: String,
        limits: FullTreeClangCaptureInputLimits,
    ): String {
        val resolved = if (raw.startsWith('/')) {
            requireCaptureAbsolutePath(raw, "capture output", limits)
        } else {
            requireCaptureRelativePath(raw, "capture output", limits)
            "$workingDirectory/$raw"
        }
        if (!resolved.startsWith("$buildRoot/")) {
            captureFail("capture output escapes the authenticated build-root namespace")
        }
        return resolved
    }

    private fun buildExpectedCaptureDocument(
        predecessors: CapturePredecessors,
        actions: ValidatedCaptureActions,
        limits: FullTreeClangCaptureInputLimits,
    ): JsonObject {
        val context = predecessors.context
        val actionCount = actions.actions.size.toLong()
        val headerCount = context.headerPaths.size.toLong()
        val sourceOnlyCount = context.sourceOnlyUnits.size.toLong()
        val environmentCount = context.baseEnvironment.size.toLong()
        val outputRecords = listOf(
            actionCount,
            headerCount,
            sourceOnlyCount,
            environmentCount,
            CAPTURE_BLOCKERS.size.toLong(),
        ).fold(0L) { total, value -> captureAddExact(total, value, "capture output record") }
        if (outputRecords > limits.maximumOutputRecords) {
            captureFail("capture input exceeds its caller-lowered output-record bound")
        }
        val workUnits = listOf(
            64L,
            captureMultiplyExact(12L, actionCount, "capture action work-unit"),
            captureMultiplyExact(4L, actions.argumentCount, "capture argument work-unit"),
            captureMultiplyExact(3L, headerCount, "capture header work-unit"),
            captureMultiplyExact(2L, sourceOnlyCount, "capture source-only work-unit"),
            captureMultiplyExact(2L, environmentCount, "capture environment work-unit"),
            captureMultiplyExact(2L, CAPTURE_BLOCKERS.size.toLong(), "capture blocker work-unit"),
        ).fold(0L) { total, value -> captureAddExact(total, value, "capture work-unit") }
        if (workUnits > limits.maximumWorkUnits) {
            captureFail("capture input exceeds its caller-lowered work-unit bound")
        }
        val withoutHash = JsonObject(
            mapOf(
                "acpBoundary" to CAPTURE_ACP_BOUNDARY,
                "actions" to JsonArray(actions.documents),
                "authority" to CAPTURE_AUTHORITY,
                "blockerDispositions" to JsonArray(CAPTURE_BLOCKER_DISPOSITIONS),
                "blockers" to JsonArray(CAPTURE_BLOCKERS),
                "bounds" to CAPTURE_BOUNDS,
                "build" to context.buildDocument,
                "canonicalCaptureHeaderCandidatePaths" to JsonArray(
                    context.headerPaths.map(::JsonPrimitive),
                ),
                "capturePolicy" to CAPTURE_POLICY,
                "commitments" to JsonObject(
                    mapOf(
                        "actionsSha256" to JsonPrimitive(actions.actionsSha256),
                        "captureContextSha256" to JsonPrimitive(context.captureContextSha256),
                        "canonicalCaptureHeaderCandidateManifestSha256" to JsonPrimitive(
                            context.headerManifestSha256,
                        ),
                    ),
                ),
                "compiler" to context.compilerDocument,
                "counts" to JsonObject(
                    mapOf(
                        "actionPathBytes" to JsonPrimitive(actions.actionPathBytes),
                        "actions" to JsonPrimitive(actions.actions.size),
                        "argumentBytes" to JsonPrimitive(actions.argumentBytes),
                        "arguments" to JsonPrimitive(actions.argumentCount),
                        "baseEnvironmentVariables" to JsonPrimitive(context.baseEnvironment.size),
                        "blockers" to JsonPrimitive(CAPTURE_BLOCKERS.size),
                        "captureHeaderCandidates" to JsonPrimitive(context.headerPaths.size),
                        "environmentBytes" to JsonPrimitive(context.environmentBytes),
                        "generatedActions" to JsonPrimitive(
                            context.modules.count { it.sourceKind == "generated" },
                        ),
                        "generatedHeaderCandidates" to JsonPrimitive(context.generatedHeaderCount),
                        "handwrittenActions" to JsonPrimitive(
                            context.modules.count { it.sourceKind == "handwritten" },
                        ),
                        "headerPathBytes" to JsonPrimitive(context.headerPathBytes),
                        "outputRecords" to JsonPrimitive(outputRecords),
                        "sourceHeaderCandidates" to JsonPrimitive(context.sourceHeaderCount),
                        "sourceModules" to JsonPrimitive(context.modules.size),
                        "sourceOnlyUnits" to JsonPrimitive(context.sourceOnlyUnits.size),
                        "workUnits" to JsonPrimitive(workUnits),
                    ),
                ),
                "environment" to context.environmentDocument,
                "generated" to context.generatedDocument,
                "kind" to JsonPrimitive("full-tree-clang-capture-input-v1"),
                "oracle" to context.oracleDocument,
                "schemaVersion" to JsonPrimitive(1),
                "source" to context.sourceDocument,
            ),
        )
        val reportSha256 = OracleArtifacts.sha256(
            OracleJson.canonicalBytes(withoutHash, controlJsonLimits(CAPTURE_MAXIMUM_CANONICAL_BYTES)),
        )
        val expected = JsonObject(withoutHash + ("reportSha256" to JsonPrimitive(reportSha256)))
        val (_, bytes) = snapshotControlObject(
            expected,
            limits.maximumCanonicalBytes,
            "full-tree Clang capture input",
            CAPTURE_SCHEMA,
        )
        if (bytes.size > limits.maximumCanonicalBytes) {
            captureFail("capture input exceeds its caller-lowered canonical byte bound")
        }
        return expected
    }

