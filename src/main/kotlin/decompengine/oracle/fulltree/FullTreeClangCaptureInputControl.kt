private fun readStableCaptureObject(
    file: StableControlFile,
    limits: FullTreeClangCaptureInputLimits,
): Pair<JsonObject, ByteArray> {
    if (file.size !in 1L..limits.maximumCanonicalBytes.toLong()) {
        captureFail("full-tree Clang capture input exceeds its byte bound")
    }
    val bytes = file.readExactly(0L, file.size.toInt(), "full-tree Clang capture input")
    val document = try {
        OracleJson.parseCanonical(bytes, controlJsonLimits(limits.maximumCanonicalBytes)) as? JsonObject
            ?: captureFail("full-tree Clang capture input root must be an object")
    } catch (failure: FullTreeControlException) {
        throw failure
    } catch (failure: Exception) {
        throw FullTreeControlException("full-tree Clang capture input is not strict canonical JSON", failure)
    }
    try {
        OracleSchemas.validate(CAPTURE_SCHEMA, document)
    } catch (failure: Exception) {
        throw FullTreeControlException("full-tree Clang capture input fails its bundled schema", failure)
    }
    return document to bytes
}

private fun validateCaptureReportHash(document: JsonObject, maximumBytes: Int) {
    val withoutHash = JsonObject(document.filterKeys { it != "reportSha256" })
    val expected = OracleArtifacts.sha256(
        OracleJson.canonicalBytes(withoutHash, controlJsonLimits(maximumBytes)),
    )
    if (document.controlString("reportSha256") != expected) {
        captureFail("full-tree Clang capture input report hash does not reconcile")
    }
}

private fun requireDistinctCaptureInputs(paths: CaptureInputPaths) {
    val normalized = paths.all().map { it.toAbsolutePath().normalize() }
    if (normalized.toSet().size != normalized.size) {
        captureFail("Clang capture input paths must be distinct")
    }
    val identities = HashSet<Any>()
    normalized.forEach { path ->
        val attributes = try {
            Files.readAttributes(path, BasicFileAttributes::class.java, LinkOption.NOFOLLOW_LINKS)
        } catch (failure: Exception) {
            throw FullTreeControlException("Clang capture input is unavailable", failure)
        }
        if (!attributes.isRegularFile || attributes.isSymbolicLink || attributes.fileKey() == null) {
            captureFail("Clang capture input path is not an identified regular file")
        }
        if (!identities.add(attributes.fileKey())) {
            captureFail("Clang capture inputs contain a physical-file alias")
        }
    }
}

private fun requireCaptureAbsolutePath(
    value: String,
    label: String,
    limits: FullTreeClangCaptureInputLimits,
): String {
    val bytes = value.toByteArray(StandardCharsets.UTF_8)
    if (!value.startsWith('/') || value == "/" || value.endsWith('/') || value.contains("//") ||
        value.any { it == '\u0000' || it == '\r' || it == '\n' || it == '\\' } ||
        bytes.size > limits.maximumPathBytes
    ) {
        captureFail("$label is not a canonical absolute path")
    }
    value.removePrefix("/").split('/').forEach { component ->
        if (component.isEmpty() || component == "." || component == ".." ||
            component.toByteArray(StandardCharsets.UTF_8).size > limits.maximumPathComponentBytes
        ) {
            captureFail("$label contains a noncanonical path component")
        }
    }
    return value
}

private fun requireCaptureRelativePath(
    value: String,
    label: String,
    limits: FullTreeClangCaptureInputLimits,
): String {
    val bytes = value.toByteArray(StandardCharsets.UTF_8)
    if (value.isEmpty() || value.startsWith('/') || value.endsWith('/') || value.contains("//") ||
        value.any { it == '\u0000' || it == '\r' || it == '\n' || it == '\\' } ||
        bytes.size > limits.maximumPathBytes
    ) {
        captureFail("$label is not a canonical relative path")
    }
    value.split('/').forEach { component ->
        if (component.isEmpty() || component == "." || component == ".." ||
            component.toByteArray(StandardCharsets.UTF_8).size > limits.maximumPathComponentBytes
        ) {
            captureFail("$label contains a noncanonical path component")
        }
    }
    return value
}

private fun requireCaptureHeaderCandidatePath(
    path: String,
    limits: FullTreeClangCaptureInputLimits,
) {
    val prefix = when {
        path.startsWith("source/") -> "source/"
        path.startsWith("generated/") -> "generated/"
        else -> captureFail("capture header candidate is outside source/generated namespaces")
    }
    requireCaptureRelativePath(path.removePrefix(prefix), "capture header candidate", limits)
    if (!CAPTURE_HEADER_SUFFIXES.any(path::endsWith)) {
        captureFail("capture header candidate has an ineligible case-sensitive suffix")
    }
}

private fun requireDisjointCaptureRoots(vararg roots: String) {
    roots.indices.forEach { leftIndex ->
        roots.indices.filter { it > leftIndex }.forEach { rightIndex ->
            val left = roots[leftIndex]
            val right = roots[rightIndex]
            if (left == right || left.startsWith("$right/") || right.startsWith("$left/")) {
                captureFail("capture physical root namespaces are equal or nested")
            }
        }
    }
}

