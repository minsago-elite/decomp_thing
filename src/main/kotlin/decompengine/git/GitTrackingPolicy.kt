package decompengine.git

/**
 * Source-only tracking policy for managed repositories (#569). The rules are written to the
 * managed repository's `info/exclude`, never into the work tree, so initialization leaves every
 * source byte and file name unchanged. Each category is explicit; a pattern never matches the
 * reconstructed C/C++ sources, headers, build descriptions or provenance manifests that make up
 * an intended source snapshot.
 */
object GitTrackingPolicy {
    const val VERSION = "source-only-v1"

    /** Top-level roots omitted when a source snapshot is copied into a work tree (archive transport layout). */
    val UNCOPIED_ROOTS = setOf("build")

    data class Category(val id: String, val description: String, val patterns: List<String>)

    val CATEGORIES = listOf(
        Category("original-binaries", "Uploaded inputs and other native binaries", listOf(
            "/input.elf", "*.elf", "*.bin", "*.exe", "*.dll", "*.so", "*.so.*", "*.dylib", "*.a", "*.lib",
            "*.o", "*.obj", "*.out",
        )),
        Category("credentials", "Credentials, keys and token files", listOf(
            ".env", ".env.*", "*.pem", "*.key", "*.p12", "*.pfx", "id_rsa*", "id_ecdsa*", "id_ed25519*",
            ".netrc", ".git-credentials", ".npmrc", ".pypirc", "*.token", "credentials.json",
        )),
        Category("job-runtime-state", "Job databases, records and staging state", listOf(
            "job.json", "workflow-state.json", "*.sqlite", "*.sqlite3", "*.db", "*.db-journal", "*.db-wal",
            ".upload-*/", ".job-metadata-*", ".git-runtime/",
        )),
        Category("private-transcripts", "Agent sessions, transcripts and progress journals", listOf(
            "/transcripts/", "/sessions/", "*.transcript", "*.jsonl", "*.ndjson",
        )),
        Category("native-build-output", "Native and generated build output", listOf(
            "/build/", "/out/", "cmake-build-*/", "CMakeFiles/", "CMakeCache.txt", "cmake_install.cmake",
            "build.ninja", ".ninja_deps", ".ninja_log", "compile_commands.json", "*.d", "*.gcda", "*.gcno",
        )),
        Category("transient-evidence", "Reports, logs and temporary evidence", listOf(
            "/reports/", "/evidence/", "*.log", "*.tmp", "*.swp", "/tmp/", "/.tmp/",
        )),
    )

    /** Exact `info/exclude` content; stable so a repository's policy can be compared later. */
    fun excludeFile(): String = buildString {
        append("# Generated by the workbench: $VERSION. Do not edit; the server owns this file.\n")
        for (category in CATEGORIES) {
            append("\n# ").append(category.id).append(": ").append(category.description).append('\n')
            category.patterns.forEach { append(it).append('\n') }
        }
    }

    private val policyLock = Any()
    private const val BATCH = 200

    /**
     * Paths this policy excludes, decided independently of the repository. In a managed repository
     * `info/exclude` only makes excluded files appear ignored, and a `.gitignore` in source content
     * outranks it (`!secret.key` would re-include a credential). The decision is therefore made in a
     * server-owned scratch repository whose only ignore source is this policy, with `--no-index`, so
     * nothing a repository contains can override it. Staging enforces this result.
     */
    internal fun prepare(runner: GitCommandRunner) { policyRepository(runner, prepare = true) }

    fun excluded(runner: GitCommandRunner, paths: Collection<String>, prepare: Boolean = true): Set<String> {
        if (paths.isEmpty()) return emptySet()
        val (gitDir, workTree) = policyRepository(runner, prepare)
        val excluded = HashSet<String>()
        fun check(batch: List<String>) = runner.run(GitInvocation("check-ignore", listOf("--no-index", "--") + batch, gitDir = gitDir,
            workTree = workTree, allowedExitCodes = setOf(0, 1),
            limits = GitExecutionLimits(java.time.Duration.ofSeconds(20), 4 * 1024 * 1024, 16 * 1024)))
        // Plain names are matched in batches by their exact output lines; names Git would quote are
        // decided one at a time by exit status, so no output parsing can confuse two names.
        val (plain, quoted) = paths.distinct().partition { path -> path.all { it.code in 0x20..0x7e && it != '"' && it != '\\' } }
        for (batch in plain.chunked(BATCH)) {
            val inputs = batch.toSet()
            check(batch).text.lineSequence().filterTo(excluded) { it in inputs }
        }
        for (path in quoted) if (check(listOf(path)).exitCode == 0) excluded += path
        return excluded
    }

    private fun policyRepository(runner: GitCommandRunner, prepare: Boolean): Pair<java.nio.file.Path, java.nio.file.Path> = synchronized(policyLock) {
        val root = runner.environment.root.resolve("policy-$VERSION")
        val gitDir = root.resolve("repository.git")
        val workTree = root.resolve("empty")
        val exclude = gitDir.resolve("info").resolve("exclude")
        val ready = java.nio.file.Files.isRegularFile(exclude, java.nio.file.LinkOption.NOFOLLOW_LINKS) &&
            java.nio.file.Files.readString(exclude) == excludeFile()
        if (!ready) {
            if (!prepare) throw GitRepositoryException("REPOSITORY_UNAVAILABLE", "The server-owned Git tracking policy is unavailable. Reads do not repair runtime storage.")
            java.nio.file.Files.createDirectories(workTree)
            if (!java.nio.file.Files.exists(gitDir.resolve("HEAD"), java.nio.file.LinkOption.NOFOLLOW_LINKS)) {
                runner.run(GitInvocation("init", listOf("--quiet", "--bare", gitDir.toString())))
            }
            java.nio.file.Files.createDirectories(exclude.parent)
            java.nio.file.Files.writeString(exclude, excludeFile())
        }
        gitDir to workTree
    }
}
